import ast
import re
import typing
from dataclasses import dataclass
from datetime import UTC, datetime
from importlib.resources import files
from pathlib import Path

from llm_ffi.function import FunctionSpec
from llm_ffi.llm_connector import LLMInterface
from llm_ffi.utils import compute_hash


def load_system_prompt() -> str:
    """Load the bundled system prompt from package data"""
    prompt_file = files("llm_ffi.prompts").joinpath("system_prompt.txt")
    return prompt_file.read_text()


def extract_function_from_generated_file(file_content: str) -> str:
    """Extract just the function source, excluding the header docstring"""
    # Find end of header docstring
    first_quote = file_content.index('"""')
    second_quote = file_content.index('"""', first_quote + 3)

    # Everything after the header
    after_header = file_content[second_quote + 3:].lstrip()

    return after_header


@dataclass
class FunctionImplementationPrefix:
    module_name: str
    function_name: str
    generated_at: str
    model_name: str
    spec_hash: str
    code_hash: str

    def to_str(self) -> str:
        return f'''"""
AUTO-GENERATED by llm-ffi - DO NOT EDIT
Module: {self.module_name}
Function: {self.function_name}
Generated: {self.generated_at}
Model: {self.model_name}
Spec Hash: {self.spec_hash}
Code Hash: {self.code_hash}
"""

'''

    @classmethod
    def from_file_content(cls, content: str) -> typing.Self:
        """Extract prefix from full file content (header + implementation)"""
        # Find the docstring at the start
        if not content.strip().startswith('"""'):
            raise ValueError("File does not start with header docstring")

        # Find the closing """
        first_quote = content.index('"""')
        second_quote = content.index('"""', first_quote + 3)
        header = content[first_quote : second_quote + 3]

        return cls.from_str(header)

    @classmethod
    def from_str(cls, content: str) -> typing.Self:
        lines = content.strip().split("\n")

        metadata = {}
        for line in lines:
            if ":" in line and line.strip() and not line.startswith('"""'):
                key, value = line.split(":", 1)
                metadata[key.strip()] = value.strip()

        return cls(
            module_name=metadata["Module"],
            function_name=metadata["Function"],
            generated_at=metadata["Generated"],
            model_name=metadata["Model"],
            spec_hash=metadata["Spec Hash"],
            code_hash=metadata["Code Hash"],
        )


def generate_implementation(spec: FunctionSpec, llm: LLMInterface) -> str:
    system_prompt = load_system_prompt()
    user_prompt = f"""Generate a Python implementation for this function spec:

{spec.source}
"""

    code = llm.infer(system_prompt, [], user_prompt)
    code = re.sub(r"^```python\n?", "", code)
    code = re.sub(r"\n?```$", "", code)

    return code


def update_spec_hashes(
    module_path: Path, specs: list[FunctionSpec], code_hashes: dict[str, str]
) -> None:
    source = module_path.read_text()
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)

    for spec in specs:
        code_hash = code_hashes[spec.name]
        new_hash_comment = f"# llm-ffi:{spec.spec_hash}:{code_hash}"

        # Find the function in AST
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name == spec.name:
                # Look for "raise NotImplementedError" in function body
                for stmt in node.body:
                    if isinstance(stmt, ast.Raise):
                        line_idx = stmt.lineno - 1  # Convert to 0-indexed
                        line = lines[line_idx]

                        # Remove existing hash comment if present
                        line = re.sub(
                            r"\s*#\s*llm-ffi:[0-9a-f]{16}:[0-9a-f]{16}", "", line
                        )

                        # Add new hash comment before newline
                        line = line.rstrip() + f"  {new_hash_comment}\n"
                        lines[line_idx] = line
                        break
                break

    module_path.write_text("".join(lines))


def generate_files(
    module_path: Path,
    specs: list[FunctionSpec],
    implementations: dict[str, str],
    model_name: str,
) -> None:
    generated_path_base = module_path.parent / f"{module_path.stem}_llm_generated"
    if not generated_path_base.exists():
        generated_path_base.mkdir()
        (generated_path_base / "__init__.py").touch()

    functions = []
    code_hashes = {}
    for spec in specs:
        function_path = generated_path_base / f"{spec.name}.llm_generated.py"
        impl = implementations[spec.name]
        code_hash = compute_hash(impl)
        code_hashes[spec.name] = code_hash

        impl_with_hash = re.sub(
            r"(def\s+" + spec.name + r"\([^)]*\)(?:\s*->\s*[^:]+)?:)",
            rf"\1  # llm-ffi:{spec.spec_hash}:{code_hash}",
            impl,
            count=1,
        )
        functions.append(impl_with_hash)
        function_path.write_text(
            FunctionImplementationPrefix(
                module_path.stem,
                spec.name,
                str(datetime.now(UTC)),
                model_name,
                spec.spec_hash,
                code_hash,
            ).to_str()
            + "\n\n"
            + impl_with_hash
        )

    update_spec_hashes(module_path, specs, code_hashes)
